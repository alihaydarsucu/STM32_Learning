static void ssd1306_write_cmd(SSD1306_t *oled, uint8_t cmd)
{
  uint8_t buf[2] = { SSD1306_CTRL_CMD, cmd };
  HAL_I2C_Master_Transmit(oled->hi2c, SSD1306_I2C_ADDR, buf, 2, 100);
}

/**
  * @brief  Initialize the SSD1306 display (128x64, I2C).
  * @param  oled: pointer to the display context
  * @param  hi2c: I2C handle
  * @retval 0 on success, 1 if the controller does not acknowledge
  */
uint8_t SSD1306_Init(SSD1306_t *oled, I2C_HandleTypeDef *hi2c)
{
  oled->hi2c = hi2c;
  memset(oled->buffer, 0, sizeof(oled->buffer));

  /* Wait for the display to be ready after power-up */
  HAL_Delay(100);

  ssd1306_write_cmd(oled, 0xAE);            /* display off            */
  ssd1306_write_cmd(oled, 0x20); ssd1306_write_cmd(oled, 0x00); /* memory mode = horizontal */
  ssd1306_write_cmd(oled, 0xB0);            /* page start address     */
  ssd1306_write_cmd(oled, 0xC8);            /* COM output scan direction: remapped */
  ssd1306_write_cmd(oled, 0x00); ssd1306_write_cmd(oled, 0x10); /* column address 0 */
  ssd1306_write_cmd(oled, 0x40);            /* start line 0           */
  ssd1306_write_cmd(oled, 0x81); ssd1306_write_cmd(oled, 0xFF); /* contrast max */
  ssd1306_write_cmd(oled, 0xA1);            /* segment remap          */
  ssd1306_write_cmd(oled, 0xA6);            /* normal display (not inverted) */
  ssd1306_write_cmd(oled, 0xA8); ssd1306_write_cmd(oled, 0x3F); /* mux 1/64 duty */
  ssd1306_write_cmd(oled, 0xA4);            /* resume from RAM content display */
  ssd1306_write_cmd(oled, 0xD3); ssd1306_write_cmd(oled, 0x00); /* display offset 0 */
  ssd1306_write_cmd(oled, 0xD5); ssd1306_write_cmd(oled, 0xF0); /* clock divide */
  ssd1306_write_cmd(oled, 0xD9); ssd1306_write_cmd(oled, 0x22); /* precharge */
  ssd1306_write_cmd(oled, 0xDA); ssd1306_write_cmd(oled, 0x12); /* COM pins config */
  ssd1306_write_cmd(oled, 0xDB); ssd1306_write_cmd(oled, 0x20); /* VCOMH deselect */
  ssd1306_write_cmd(oled, 0x8D); ssd1306_write_cmd(oled, 0x14); /* charge pump on */
  ssd1306_write_cmd(oled, SSD1306_CMD_DISPLAY_ON);

  return 0;
}

/**
  * @brief  Set every pixel in the framebuffer to black.
  */
void SSD1306_Clear(SSD1306_t *oled)
{
  memset(oled->buffer, 0, sizeof(oled->buffer));
}

/**
  * @brief  Fill the whole framebuffer with one color.
  */
void SSD1306_Fill(SSD1306_t *oled, SSD1306_COLOR_t color)
{
  memset(oled->buffer, color == SSD1306_COLOR_WHITE ? 0xFF : 0x00,
         sizeof(oled->buffer));
}

/**
  * @brief  Push the framebuffer to the display.
  */
void SSD1306_Update(SSD1306_t *oled)
{
  static const uint8_t col_addr[] = { SSD1306_CTRL_CMD,
    SSD1306_CMD_SET_COL_ADDR, 0, SSD1306_WIDTH - 1 };
  static const uint8_t page_addr[] = { SSD1306_CTRL_CMD,
    SSD1306_CMD_SET_PAGE_ADDR, 0, (SSD1306_HEIGHT / 8) - 1 };

  HAL_I2C_Master_Transmit(oled->hi2c, SSD1306_I2C_ADDR,
                          (uint8_t *)col_addr, sizeof(col_addr), 100);
  HAL_I2C_Master_Transmit(oled->hi2c, SSD1306_I2C_ADDR,
                          (uint8_t *)page_addr, sizeof(page_addr), 100);

  HAL_I2C_Mem_Write(oled->hi2c, SSD1306_I2C_ADDR, 0x40,
                    I2C_MEMADD_SIZE_8BIT, oled->buffer, sizeof(oled->buffer), 100);
}

/**
  * @brief  Turn a single pixel on/off in the framebuffer.
  */
void SSD1306_DrawPixel(SSD1306_t *oled, uint16_t x, uint16_t y, SSD1306_COLOR_t color)
{
  if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT)
  {
    return;
  }
  uint16_t idx = x + (y / 8) * SSD1306_WIDTH;
  uint8_t bit = 1u << (y % 8);
  if (color == SSD1306_COLOR_WHITE)
  {
    oled->buffer[idx] |= bit;
  }
  else
  {
    oled->buffer[idx] &= ~bit;
  }
}

/**
  * @brief  Draw a single character into the framebuffer.
  * @note   size 1 => 8x8, size 2 => 16x16.
  */
void SSD1306_DrawChar(SSD1306_t *oled, uint16_t x, uint16_t y, char ch,
                      SSD1306_COLOR_t color)
{
  if (ch < 0x20 || ch > 0x7F)
  {
    ch = ' ';
  }
  for (uint8_t i = 0; i < 5; i++)
  {
    uint8_t line = ssd1306_font5x7[ch - 0x20][i];
    for (uint8_t j = 0; j < 8; j++)
    {
      if (line & (1u << j))
      {
        SSD1306_DrawPixel(oled, x + i, y + j, color);
      }
      else
      {
        SSD1306_DrawPixel(oled, x + i, y + j, SSD1306_COLOR_BLACK);
      }
    }
  }
}

/**
  * @brief  Write a whole string into the framebuffer.
  * @note   size 1 => 8x8, size 2 => 16x16 (still renders 5x7, pixel doubled).
  */
void SSD1306_WriteString(SSD1306_t *oled, uint16_t x, uint16_t y, const char *str,
                         SSD1306_COLOR_t color, uint8_t size)
{
  while (*str)
  {
    SSD1306_DrawChar(oled, x, y, *str++, color);
    x += 6 * size;
    if (x >= SSD1306_WIDTH)
    {
      break;
    }
  }
}
